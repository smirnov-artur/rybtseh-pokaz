/*!
 * KLEVTSOV FISH HOUSE — EN-only sibling of assets/schema.js.
 * Same generators (BreadcrumbList, Product, VideoObject, Organization),
 * with the English strings the English pages need. The shared RU
 * assets/schema.js is untouched; RU pages keep using it as before.
 *
 * Usage — same as the RU file: include it, then call a builder and
 * inject the result as its own <script type="application/ld+json">:
 *
 *   RybtsehSchema.inject(RybtsehSchema.breadcrumbList());
 *   RybtsehSchema.inject(RybtsehSchema.organization());
 */
(function (window, document) {
  'use strict';

  var BASE_URL = window.RYBTSEH_SCHEMA_BASE_URL || 'https://xn--90ai5awd2a.xn--p1ai/';
  var BUSINESS_ID = BASE_URL + '#business';

  function absUrl(path) {
    path = String(path || '').replace(/^\/+/, '');
    return BASE_URL + path;
  }

  /* ---------- inject a ready object as its own <script> ---------- */
  function inject(ld) {
    if (!ld) return null;
    var s = document.createElement('script');
    s.type = 'application/ld+json';
    s.textContent = JSON.stringify(ld);
    document.head.appendChild(s);
    return s;
  }

  /* BREADCRUMBLIST — by the current page's file name. No breadcrumbs on
     the home page (one useless element) or on 404. */
  var PAGE_TITLES = {
    'index.html': 'Home',
    'price.html': 'Price list',
    'istoria.html': 'Our story',
    'opt.html': 'Wholesale',
    'dostavka.html': 'Delivery',
    'magazin.html': 'Shop'
  };

  function currentFile() {
    var f = String(location.pathname || '').split('/').pop();
    return f || 'index.html';
  }

  function breadcrumbList(label) {
    var file = currentFile();
    if (file === 'index.html' || file === '' || file === '404.html') return null;

    var name = label || PAGE_TITLES[file] ||
      (document.title || '').split(/[—-]/)[0].trim() || file;

    return {
      '@context': 'https://schema.org',
      '@type': 'BreadcrumbList',
      'itemListElement': [
        {
          '@type': 'ListItem',
          'position': 1,
          'name': 'Home',
          'item': absUrl('index.html')
        },
        {
          '@type': 'ListItem',
          'position': 2,
          'name': name,
          'item': absUrl(file)
        }
      ]
    };
  }

  /* FAQPAGE — not applicable, same as the RU file: no real Q&A blocks
     on these pages. Left as a stub, returns null without pairs. */
  function faqPage(pairs) {
    if (!pairs || !pairs.length) return null;
    return {
      '@context': 'https://schema.org',
      '@type': 'FAQPage',
      'mainEntity': pairs.map(function (p) {
        return {
          '@type': 'Question',
          'name': p.q,
          'acceptedAnswer': { '@type': 'Answer', 'text': p.a }
        };
      })
    };
  }

  /* PRODUCT — from window.PRICES (en/prices.js on the English pages).
     Same shape as the inline ItemList script on price.html; don't add
     this on top of that inline script (avoids a duplicate JSON-LD block). */
  function productList(pageUrl) {
    var P = window.PRICES;
    if (!P || !P.items || !P.items.length) return null;
    var url = pageUrl ? absUrl(pageUrl) : absUrl('price.html');
    return {
      '@context': 'https://schema.org',
      '@type': 'ItemList',
      'name': 'Klevtsov Fish House price list',
      'description': P.vat_note || '',
      'url': url,
      'numberOfItems': P.items.length,
      'itemListOrder': 'https://schema.org/ItemListUnordered',
      'itemListElement': P.items.map(function (it, n) {
        return {
          '@type': 'ListItem',
          'position': n + 1,
          'item': productSingle(it, url)
        };
      })
    };
  }

  function productSingle(it, pageUrl) {
    var P = window.PRICES || {};
    var url = pageUrl || absUrl('price.html');
    return {
      '@type': 'Product',
      'name': it.name + (it.variant ? ', ' + it.variant : ''),
      'category': it.category,
      'brand': { '@type': 'Brand', 'name': 'Klevtsov Fish House' },
      'offers': {
        '@type': 'Offer',
        'price': it.price_retail,
        'priceCurrency': P.currency || 'RUB',
        'url': url,
        'eligibleQuantity': { '@type': 'QuantitativeValue', 'unitText': it.unit }
        /* availability intentionally omitted */
      }
    };
  }

  /* VIDEOOBJECT — scans the page's own <video> elements, same detection
     as the RU file (by source path, not by a hardcoded file name). */
  var DURATION_BY_KIND = {
    production_film: 'PT35S',
    report_1tv: 'PT3M40S'
  };

  var DESCRIPTION_BY_KIND = {
    production_film: 'A staged short about curing fish: intake, salting, the drying room. ' +
      'Generated by AI in 2026 — not documentary footage of the workshop, an illustration ' +
      'of the process, without sound.',
    report_1tv: 'A Channel One television report on Klevtsov Fish House, aired ' +
      'August 25, 2008: real footage of intake, salting and drying, with sound.'
  };

  var NAME_BY_KIND = {
    production_film: 'A film about curing fish — Klevtsov Fish House',
    report_1tv: 'Channel One on Klevtsov Fish House, aired 25.08.2008'
  };

  var UPLOAD_DATE_BY_KIND = {
    production_film: window.RYBTSEH_SCHEMA_FILM_DATE || null,
    report_1tv: '2008-08-25'
  };

  function findVideoEl(kind) {
    var all = document.querySelectorAll('video');
    for (var i = 0; i < all.length; i++) {
      var v = all[i];
      var src = '';
      var sourceEl = v.querySelector('source');
      src = (sourceEl && sourceEl.getAttribute('src')) || v.getAttribute('src') || '';
      src = src.toLowerCase();
      if (kind === 'report_1tv' && src.indexOf('1tv') !== -1) return v;
      if (kind === 'production_film' && src.indexOf('1tv') === -1 &&
        (src.indexOf('kino') !== -1 || src.indexOf('film') !== -1)) return v;
    }
    return null;
  }

  function videoObject(kind) {
    var v = findVideoEl(kind);
    if (!v) return null;

    var sourceEl = v.querySelector('source');
    var src = (sourceEl && sourceEl.getAttribute('src')) || v.getAttribute('src') || '';
    var poster = v.getAttribute('poster') || '';
    var uploadDate = UPLOAD_DATE_BY_KIND[kind];

    var ld = {
      '@context': 'https://schema.org',
      '@type': 'VideoObject',
      'name': NAME_BY_KIND[kind] || document.title,
      'description': DESCRIPTION_BY_KIND[kind] || '',
      'thumbnailUrl': poster ? [absUrl(poster)] : undefined,
      'contentUrl': src ? absUrl(src) : undefined,
      'embedUrl': absUrl(currentFile()),
      'duration': DURATION_BY_KIND[kind]
    };
    if (uploadDate) ld.uploadDate = uploadDate;
    return ld;
  }

  /* ORGANIZATION — role contacts, English labels. Same @id as the
     LocalBusiness on index.html so Google treats it as one entity. */
  function organization() {
    return {
      '@context': 'https://schema.org',
      '@type': 'Organization',
      '@id': BUSINESS_ID,
      'name': 'Klevtsov Fish House',
      'alternateName': 'Klevtsov Fishworks',
      'url': BASE_URL,
      'logo': absUrl('apple-touch-icon-180.png'),
      'foundingDate': '1967',
      'sameAs': ['https://vk.com/klevtsov_fish'],
      'contactPoint': [
        {
          '@type': 'ContactPoint',
          'contactType': 'sales',
          'name': 'Wholesale — Anton Dmitrievich',
          'telephone': '+7-928-770-21-70',
          'email': 'ak806@me.com',
          'availableLanguage': 'Russian'
        },
        {
          '@type': 'ContactPoint',
          'contactType': 'customer support',
          'name': 'Retail — Margarita Georgievna',
          'telephone': '+7-918-594-96-85',
          'availableLanguage': 'Russian'
        },
        {
          '@type': 'ContactPoint',
          'contactType': 'technical support',
          'name': 'Quality lead — Olga Mikhaylovna',
          'telephone': '+7-928-96-500-95',
          'email': 'info@k-fish.ru',
          'availableLanguage': 'Russian'
        }
      ]
    };
  }

  function clean(o) {
    if (!o || typeof o !== 'object') return o;
    if (Array.isArray(o)) { return o.map(clean); }
    var out = {};
    Object.keys(o).forEach(function (k) {
      if (o[k] === undefined) return;
      out[k] = clean(o[k]);
    });
    return out;
  }

  window.RybtsehSchema = {
    inject: function (ld) { return inject(clean(ld)); },
    breadcrumbList: breadcrumbList,
    faqPage: faqPage,
    productList: productList,
    productSingle: productSingle,
    videoObject: videoObject,
    organization: organization,
    _clean: clean,
    _absUrl: absUrl
  };

})(window, document);
